import { pickOne } from "@/lib/buoy";

// "밤의 우체통" 형태. 사전 자체는 우리가 정한다.
const TIMES = [
  "밤", "새벽", "낮달", "저녁", "자정", "초저녁", "여명", "한밤", "새벽녘", "노을",
  "은하수", "별밤", "물빛", "달무리",
];
const NOUNS = [
  "우체통", "방파제", "등대", "파도", "부표", "돛", "항구", "물결", "조약돌",
  "모래톱", "썰물", "밀물", "닻", "갈매기", "부둣가", "수평선", "안개", "별자리", "파문", "닻줄",
  "물방울", "산호", "불가사리", "소라", "물거품", "반딧불", "이슬", "고래", "수달",
  "별똥별", "조개", "파랑새", "달팽이", "민들레", "고양이",
];

/** 순수 함수. 유니크 보장은 안 함 — DB unique 제약 + 재시도로 처리한다. */
export function generateNickname(): string {
  const time = pickOne(TIMES) ?? "밤";
  const noun = pickOne(NOUNS) ?? "부표";
  return `${time}의 ${noun}`;
}
